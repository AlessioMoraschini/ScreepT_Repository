package junit;

import java.util.Random;

import org.junit.Test;

import crypt.steg.ImageCodeDecode;
import gUI.om.BufferedImageType;
import uTILS.local.ImageWorker;

public class TestByteIntConversion_ImagesStuff {
	
	private final int MAX3Bytes = (int) (Math.pow(2.0d, 24.0d)-1);
	private final int MIN3Bytes = - (int) (Math.pow(2.0d, 24.0d)-1);
	
	//////////////////////////////////////////////////////////////////
	//////////////////INITIALIZE VARIABLES FOR TEST //////////////////
	//////////////////////////////////////////////////////////////////
	
	int sourceInt, B,SUM;
	int A;
	
	byte[] byteSrc = new byte[4];
	Random generator;
	
	///////////////////////////////////////////////////////////////
	//////////////////////START TEST METHODS //////////////////////
	///////////////////////////////////////////////////////////////
	
	@Test
	public void test3FromInt() {
		print(" => 3byte - TEST FROM INT\n");
		
		initInt();
		byteSrc = ImageCodeDecode.retrieveBytesFromInt(sourceInt);
		print("Generated Integer: "+sourceInt);
		print("Retrieved Bytes: ["+byteSrc[0]+", "+byteSrc[1]+", "+byteSrc[2]+", "+byteSrc[3]+"] ");
		
		sourceInt = ImageCodeDecode.threeBytesToIntShift(byteSrc[1], byteSrc[2], byteSrc[3]);
		print("Back 3bytes to int: "+sourceInt+"\n");
	
		separatorPrint();
	}
	
	@Test
	public void test3FromByte() {
		print(" => 3 byte - TEST FROM BYTE\n");
		
		initBytes();
		sourceInt = ImageCodeDecode.threeBytesToIntShift(byteSrc[1], byteSrc[2], byteSrc[3]);
		print("Generated Bytes: ["+byteSrc[0]+", "+byteSrc[1]+", "+byteSrc[2]+", "+byteSrc[3]+"] ");
		print("Retrieved int: "+sourceInt);
		
		byteSrc = ImageCodeDecode.retrieveBytesFromInt(sourceInt);
		print("Now back to Bytes: ["+byteSrc[0]+", "+byteSrc[1]+", "+byteSrc[2]+", "+byteSrc[3]+"]\n");
		
		separatorPrint();
	}
	
	@Test
	public void testSecureShiftSum() {
		print(" => TEST secure byte\n");
		
		A = Integer.MAX_VALUE;
		generator = new Random();
		//B = generator.nextInt(MAX3Bytes);
		B = MAX3Bytes;
		SUM = A+B;
		print("Int valueA: "+A);
		print("Int valueB: "+B);
		print("SUM before secure: "+SUM+"\n");
		
		A = ImageCodeDecode.secureRightShift(A);
		SUM = A+B;
		print("Int Sec_valueA: "+A);
		print("Int valueB: "+B);
		print("SUM after secure: "+SUM+"\n");
		
		separatorPrint();
	}
	
	@Test
	public void testNegativeSecureShiftSum() {
		print(" => TEST secure byte subctraction\n");
		
		A = Integer.MIN_VALUE;
		generator = new Random();
		//B = generator.nextInt(MAX3Bytes);
		B = MIN3Bytes;
		SUM = A+B;
		print("Int valueA: "+A);
		print("Int valueB: "+B);
		print("A+B before secure: "+SUM+"\n");
		
		A = ImageCodeDecode.secureRightShift(A);
		SUM = A+B;
		print("Int Sec_valueA: "+A);
		print("Int valueB: "+B);
		print("A+B after secure: "+SUM+"\n");
		
		separatorPrint();
	}
	
	@Test
	public void testPossibleBitsPerPX() {
		print(" => TEST image types bit X pixel\n");
		for(BufferedImageType current : BufferedImageType.values()) {
			int bitSize = ImageWorker.generaKeyImage(20, 20, current.getType()).getColorModel().getPixelSize();
			print(" => Type: "+current+", SIZE in bits: "+bitSize);
		}
		separatorPrint();
	}
	
	////////////////////////////////////////////////////////////////
	//////////////////////		GENERATORS	  //////////////////////
	////////////////////////////////////////////////////////////////
	
	private void initBytes() {
		generator = new Random();
		generator.nextBytes(byteSrc);
	}
	
	private void initInt() {
		generator = new Random();
		sourceInt = generator.nextInt(MAX3Bytes);
	}
	
	// lazy printer
	private void print(Object src) {
		System.out.println(src);
	}
	
	private void separatorPrint() {
		print("\n   ###################################################\n");
	}
	
}
