package mainlauncher;

import java.io.File;
import java.io.IOException;
import java.nio.charset.Charset;
import java.nio.file.Files;
import java.util.List;

import os.commons.utils.SysUtils;
import resources.GeneralConfig;

/**
 * Fast start: when the launcher is set to start directly ("hide launcher at start") the starter file written by a previous
 * clean launch (LauncherBatch.bat / LauncherBash.sh) is reused, skipping the whole launcher initialization.
 * The full launcher runs only when the starter is missing, outdated, points to a Java that is gone, or the application
 * does not come up after the fast start.
 */
public final class ExistingStarterReuse {

	/** Marker written next to the starter: its content is the signature of what the starter was generated from */
	private static final String VERIFIED_SUFFIX = ".verified";

	/** How long to wait for the application to announce itself (signal file) after a fast start */
	private static final long APP_START_TIMEOUT_MS = 20000;
	private static final long POLL_MS = 150;

	/** Set when a fast start did not bring the application up: the launcher window must be shown instead of retrying blindly */
	public static volatile boolean fastStartFailed = false;

	private ExistingStarterReuse() {
	}

	/**
	 * Marks the starter just generated as reusable. Call it only when it was generated by a clean direct launch
	 * with no arguments, because file arguments are written inside the starter.
	 */
	public static void markVerified() {
		try {
			Files.write(markerFile().toPath(), signature().getBytes(Charset.defaultCharset()));
		} catch (IOException | RuntimeException e) {
			ScreepTLauncher.logger.warn("Cannot mark the starter as reusable: " + e);
		}
	}

	/**
	 * Starts the application through the existing starter, if it is still valid.
	 *
	 * @return true if the application has been started (the launcher can exit), false to continue with the
	 *         normal launcher flow; in the latter case {@link #fastStartFailed} tells if the starter was launched in vain
	 */
	public static boolean tryFastStart(boolean hiddenShell) {
		try {
			File starter = new File(ScreepTLauncher.generatedNativeLauncherPath);
			File marker = markerFile();
			if (!starter.isFile() || !marker.isFile()) {
				return false;
			}
			// regenerated later by the launcher panel (custom options, arguments...): not a clean starter anymore
			if (starter.lastModified() > marker.lastModified()) {
				return false;
			}
			String verifiedSignature = new String(Files.readAllBytes(marker.toPath()), Charset.defaultCharset());
			if (!verifiedSignature.equals(signature()) || !javaOfStarterExists(starter)) {
				return false;
			}

			SysUtils.launchBatchOrBash(ScreepTLauncher.generatedNativeLauncherPath, hiddenShell);
			if (waitForApplication()) {
				return true;
			}

			// launched but the application never showed up: show the launcher and don't trust this starter again
			marker.delete();
			fastStartFailed = true;
			return false;

		} catch (Exception e) {
			return false;
		}
	}

	/** The application writes its signal file at startup: when it exists, the application is on its way */
	private static boolean waitForApplication() {
		File signal = GeneralConfig.SCREEPT_ACTIVE_SIGNAL_FILE;
		if (signal == null) {
			return true; // nothing to check against
		}
		long deadline = System.currentTimeMillis() + APP_START_TIMEOUT_MS;
		while (System.currentTimeMillis() < deadline) {
			if (signal.exists()) {
				return true;
			}
			try {
				Thread.sleep(POLL_MS);
			} catch (InterruptedException e) {
				Thread.currentThread().interrupt();
				return signal.exists();
			}
		}
		return signal.exists();
	}

	/** The Java the starter was generated for must still be there (empty path means "the one in the PATH") */
	private static boolean javaOfStarterExists(File starter) throws IOException {
		List<String> lines = Files.readAllLines(starter.toPath(), Charset.defaultCharset());
		for (String line : lines) {
			String javaDir = null;
			if (line.startsWith("set JDK_PATH=")) {
				javaDir = line.substring("set JDK_PATH=".length()).trim();
				javaDir = javaDir.endsWith(";") ? javaDir.substring(0, javaDir.length() - 1) : javaDir;
			} else if (line.startsWith("PATH=") && line.contains(":$PATH")) {
				javaDir = line.substring("PATH=".length(), line.lastIndexOf(":$PATH")).trim();
			}
			if (javaDir == null) {
				continue;
			}
			if (javaDir.isEmpty()) {
				return true;
			}
			File dir = new File(javaDir.trim());
			return new File(dir, "javaw.exe").isFile() || new File(dir, "java.exe").isFile() || new File(dir, "java").isFile();
		}
		return true;
	}

	private static File markerFile() {
		return new File(ScreepTLauncher.generatedNativeLauncherPath + VERIFIED_SUFFIX);
	}

	/** Anything the starter depends on: launcher ini, main jar and this launcher jar (name, size, date) */
	private static String signature() {
		return describe(new File(ScreepTLauncher.DEFAULT_INI_PATH))
				+ describe(new File(ScreepTLauncher.iniFileManager.MAIN_JAR_FILE))
				+ describe(ownJar());
	}

	private static String describe(File file) {
		if (file == null || !file.isFile()) {
			return "-;";
		}
		return file.getName() + "|" + file.length() + "|" + file.lastModified() + ";";
	}

	private static File ownJar() {
		try {
			return new File(ExistingStarterReuse.class.getProtectionDomain().getCodeSource().getLocation().toURI());
		} catch (Exception e) {
			return null;
		}
	}
}
